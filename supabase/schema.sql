-- Crop Circles platform tables. Run once in Supabase: Dashboard > SQL Editor > New query > paste > Run.
-- Accounts themselves live in Supabase Auth (auth.users); profiles adds the app's name, role and region.
-- RLS is on with no policies: the publishable key can read nothing, only the server (secret key) can.

create table if not exists public.profiles (
  id      uuid primary key references auth.users (id) on delete cascade,
  name    text unique not null,              -- short account name used across the app (anna, berater, ...)
  email   text unique not null,              -- what Supabase Auth signs in with
  display text not null,
  role    text not null check (role in ('farmer', 'advisor', 'authority', 'admin')),
  region  text not null
);

create table if not exists public.user_fields (   -- which demo field (F1..F3) a farmer owns
  account text references public.profiles (name) on update cascade on delete cascade,
  field   text,
  primary key (account, field)
);

create table if not exists public.parcels (       -- FIONA parcels a farmer added from the region map
  account text references public.profiles (name) on update cascade on delete cascade,
  parcel  bigint,
  added   timestamptz not null default now(),
  primary key (account, parcel)
);

create table if not exists public.posts (
  id      bigint generated by default as identity primary key,
  author  text references public.profiles (name) on update cascade on delete set null,
  region  text not null,
  kind    text not null check (kind in ('note', 'question', 'alert')),
  field   text not null default '',
  text    text not null,
  created timestamptz not null default now()
);

create table if not exists public.replies (
  id      bigint generated by default as identity primary key,
  post    bigint not null references public.posts (id) on delete cascade,
  author  text references public.profiles (name) on update cascade on delete set null,
  text    text not null,
  created timestamptz not null default now()
);

create index if not exists posts_region_idx on public.posts (region, id desc);
create index if not exists replies_post_idx on public.replies (post, id);

alter table public.profiles    enable row level security;
alter table public.user_fields enable row level security;
alter table public.parcels     enable row level security;
alter table public.posts       enable row level security;
alter table public.replies     enable row level security;
